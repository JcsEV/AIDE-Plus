	public static void writerEmptyZip(String path) throws IOException{
		writerEmptyZip(new File(path));
	}
	public static void writerEmptyZip( File file) throws IOException{
		FileOutputStream outputStream = null;
		try{
			outputStream = new FileOutputStream(file);
			outputStream.write(Utils.EmptyZip);
		}
		finally{
			IOUtils.close(outputStream);
		}

	}


	public static long nowTime(){
		return System.currentTimeMillis();
	}


	public static int parseInt(String parseInt, int defaultValue){
		try {
			return Integer.parseInt(parseInt);
		} catch (NumberFormatException e) {
			return defaultValue;
		}
	}
